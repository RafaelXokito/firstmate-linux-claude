#!/usr/bin/env bash
# Enter the firstmate home that serves the current directory.
#
# This is the operator entry point for the per-project layout created by
# bin/fm-project-home.sh: the captain cd's into any project and runs `fm`, and
# this script finds that project's own home, converges it, and starts the harness
# there. It is the ONLY thing that has to know where a home is; every tracked
# script keeps resolving its directories from FM_HOME and FM_ROOT exactly as
# before.
#
# Two variables are exported for every child process, and both are required:
#   FM_HOME           <project>/.firstmate - the operational home
#   FM_ROOT_OVERRIDE  the shared tracked clone - the code root
# FM_ROOT_OVERRIDE is not optional convenience. Without it a script reached
# through the home resolves its code root to the home, which aims the
# worktree-tangle guard at the PROJECT's branch and alarms on every feature
# branch. docs/configuration.md's "FM_HOME" section owns what each variable
# selects.
#
# Home resolution, in order:
#   1. an explicit FM_HOME already in the environment, used unchanged
#   2. the nearest enclosing <dir>/.firstmate carrying a per-project marker
#   3. the shared clone itself, when the caller is inside it - the classic
#      whole-repo layout, where the code root IS the home
# A caller in none of those is refused with the init command to run, rather than
# defaulting to a home that serves some other project.
#
# Usage: fm-launch.sh [<harness args...>]     converge, then exec the harness in the home
#        fm-launch.sh init [<project-dir>] [--name <n>] [--mode <m>] [--yolo on|off]
#        fm-launch.sh env [<dir>]             print the two exports for eval
#        fm-launch.sh status [<dir>]          print the resolved home, root, project
#        fm-launch.sh run <fm-script.sh> [args...]   run one tracked bin script in the home
#        fm-launch.sh alias [<dest-dir>]      install the `fm` shim (default ~/.local/bin)
#
# The harness is `claude` unless FM_LAUNCH_CMD names another command; it is
# exec'd with the home as its working directory, so it loads the home's CLAUDE.md
# pointer to the shared AGENTS.md and still inherits the project's own CLAUDE.md
# from the parent directory. `run` refuses anything but a real executable in this
# clone's bin/fm-*.sh namespace, the same restriction bin/fm-on.sh applies to a
# remote command.
set -eu

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="$(cd "$SCRIPT_DIR/.." && pwd -P)"

usage() { sed -n '/^# Usage:/,/^# remote command\./p' "$0" | sed 's/^# \{0,1\}//'; }
die() { echo "error: $*" >&2; exit 1; }

# Echo the home serving <dir>, or return 1 with the reason on stderr.
resolve_home() {
  local dir=$1 home
  if [ -n "${FM_HOME:-}" ]; then
    (cd "$FM_HOME" && pwd -P) || return 1
    return 0
  fi
  if home=$("$FM_ROOT/bin/fm-project-home.sh" path "$dir" 2>/dev/null); then
    printf '%s\n' "$home"
    return 0
  fi
  dir=$(cd "$dir" && pwd -P) || return 1
  case "$dir" in
    "$FM_ROOT"|"$FM_ROOT"/*) printf '%s\n' "$FM_ROOT"; return 0 ;;
  esac
  echo "error: no firstmate home serves $dir" >&2
  echo "hint: run 'fm init' at the top of the project you want a home for" >&2
  return 1
}

# Bring a per-project home back to its expected shape before anything runs in it.
# Idempotent, and silent unless it fails; the classic whole-repo layout has
# nothing to converge.
converge_home() {
  local home=$1 project
  [ -f "$home/.fm-project-home" ] || return 0
  project=$(sed -n 's/^project=//p' "$home/.fm-project-home" | head -1)
  [ -n "$project" ] || die "$home/.fm-project-home has no project= line; recreate the home with 'fm init'"
  [ -d "$project" ] || die "the project this home serves is missing: $project"
  "$FM_ROOT/bin/fm-project-home.sh" init "$project" >/dev/null
}

cmd_env() {
  local home
  home=$(resolve_home "${1:-$PWD}") || exit 1
  printf 'export FM_HOME=%s\n' "$home"
  printf 'export FM_ROOT_OVERRIDE=%s\n' "$FM_ROOT"
}

cmd_run() {
  local home script
  script=${1:?usage: fm-launch.sh run <fm-script.sh> [args...]}
  shift
  case "$script" in
    */*) die "run takes a bare script name, not a path: $script" ;;
    fm-*.sh) ;;
    *) die "run takes a tracked bin/fm-*.sh script name, not '$script'" ;;
  esac
  [ -x "$FM_ROOT/bin/$script" ] || die "no executable bin/$script in $FM_ROOT"
  home=$(resolve_home "$PWD") || exit 1
  converge_home "$home"
  FM_HOME="$home" FM_ROOT_OVERRIDE="$FM_ROOT" exec "$FM_ROOT/bin/$script" "$@"
}

cmd_alias() {
  local dest=${1:-$HOME/.local/bin} target
  mkdir -p "$dest"
  target="$dest/fm"
  if [ -e "$target" ] && ! [ -f "$target" ]; then
    die "$target exists and is not a regular file; move it aside and rerun"
  fi
  cat > "$target" <<EOF
#!/bin/sh
# Generated by fm-launch.sh alias; regenerate rather than editing.
exec "$FM_ROOT/bin/fm-launch.sh" "\$@"
EOF
  chmod 0755 "$target"
  echo "installed: $target -> $FM_ROOT/bin/fm-launch.sh"
  case ":$PATH:" in
    *":$dest:"*) ;;
    *) echo "warning: $dest is not on PATH; add it to use plain 'fm'" >&2 ;;
  esac
}

cmd_launch() {
  local home
  home=$(resolve_home "$PWD") || exit 1
  converge_home "$home"
  cd "$home"
  FM_HOME="$home" FM_ROOT_OVERRIDE="$FM_ROOT" exec "${FM_LAUNCH_CMD:-claude}" "$@"
}

case "${1:-}" in
  init) shift; exec "$FM_ROOT/bin/fm-project-home.sh" init "$@" ;;
  status) shift; exec "$FM_ROOT/bin/fm-project-home.sh" status "$@" ;;
  env) shift; cmd_env "$@" ;;
  run) shift; cmd_run "$@" ;;
  alias) shift; cmd_alias "$@" ;;
  -h|--help) usage ;;
  *) cmd_launch "$@" ;;
esac
